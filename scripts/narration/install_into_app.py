#!/usr/bin/env python3
"""Copy finished narration into the app and regenerate the registry the app reads.

usage: install_into_app.py "Genesis" [--src ~/Desktop/Narration/Genesis]

For every chapter in SRC that has BOTH <Book>_<NNN>.m4a and <Book>_<NNN>.json, copies
the pair to assets/narration/<Book>/ and then rewrites constants/audio/bundledNarration.ts
from everything under assets/narration/ (so running it for several books accumulates).
Metro needs static require() calls, which is why the registry is generated.
"""
import argparse, glob, json, os, re, shutil

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ASSETS = os.path.join(REPO, "assets/narration")
REGISTRY = os.path.join(REPO, "constants/audio/bundledNarration.ts")


def book_slug(book):
    return re.sub(r"\s+", "_", re.sub(r"[()]", "", book).strip())


def write_registry():
    entries = []
    for meta_path in sorted(glob.glob(os.path.join(ASSETS, "*", "*.json"))):
        m4a = meta_path[:-5] + ".m4a"
        if not os.path.exists(m4a):
            continue
        meta = json.load(open(meta_path))
        rel = os.path.relpath(meta_path, REPO)[:-5]          # assets/narration/Genesis/Genesis_001
        entries.append((meta["book"], meta["chapter"], rel))
    lines = [
        "// GENERATED by scripts/narration/install_into_app.py — do not edit by hand.",
        "// Chapters of narration that ship inside the app (assets/narration/). Anything not",
        "// listed here is streamed from the audio server instead (see PremiumNarrationService).",
        'import { ChapterAudioMetadata } from "./types";',
        "",
        "export interface BundledChapter {",
        "  metadata: ChapterAudioMetadata;",
        "  /** Metro asset id for the audio file — pass straight to createAudioPlayer. */",
        "  audio: number;",
        "}",
        "",
        "const BUNDLED: Record<string, BundledChapter> = {",
    ]
    for book, chapter, rel in entries:
        lines.append(f'  "{book} {chapter}": {{')
        lines.append(f'    metadata: require("@/{rel}.json") as ChapterAudioMetadata,')
        lines.append(f'    audio: require("@/{rel}.m4a") as number,')
        lines.append("  },")
    lines += ["};", "", "export function bundledNarration(book: string, chapter: number): BundledChapter | undefined {",
              "  return BUNDLED[`${book} ${chapter}`];", "}", ""]
    open(REGISTRY, "w").write("\n".join(lines))
    return len(entries)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("book")
    ap.add_argument("--src", default=None)
    a = ap.parse_args()
    slug = book_slug(a.book)
    src = os.path.expanduser(a.src or f"~/Desktop/Narration/{slug}")
    dst = os.path.join(ASSETS, slug)
    os.makedirs(dst, exist_ok=True)
    copied = 0
    for meta in sorted(glob.glob(os.path.join(src, f"{slug}_[0-9][0-9][0-9].json"))):
        m4a = meta[:-5] + ".m4a"
        if not os.path.exists(m4a):
            continue
        for f in (meta, m4a):
            target = os.path.join(dst, os.path.basename(f))
            if not os.path.exists(target) or os.path.getmtime(f) > os.path.getmtime(target):
                shutil.copy2(f, target)
        copied += 1
    n = write_registry()
    size = sum(os.path.getsize(f) for f in glob.glob(os.path.join(ASSETS, "*", "*.m4a"))) / 1e6
    print(f"{slug}: {copied} chapters found in {src}; registry now lists {n} chapters ({size:.0f} MB of audio in the app)")


if __name__ == "__main__":
    main()
