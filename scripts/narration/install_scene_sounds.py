#!/usr/bin/env python3
"""Install scene-sound files into the app and regenerate the registry the app reads.

usage: install_scene_sounds.py [--src DIR] [--allow-unlicensed] [--clean]

* --src DIR   copy every .m4a/.mp3 in DIR into assets/scene-sounds/ first
* then rewrites constants/audio/sceneSoundFiles.ts from everything in assets/scene-sounds/
  (Metro needs static require() calls, which is why the registry is generated)
* every sound must have an entry in assets/scene-sounds/LICENSES.json —
    { "wind-over-water": {"source": "Freesound", "url": "...", "license": "CC0", "author": "..."} }
  — or the install stops. App Review can ask where sounds come from, so the record is kept with the files.
  --allow-unlicensed skips that check (throwaway test sounds only — never commit those).
* --clean     remove all installed sounds and write an empty registry
"""
import argparse, glob, json, os, shutil, sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DIR = os.path.join(REPO, "assets/scene-sounds")
REGISTRY = os.path.join(REPO, "constants/audio/sceneSoundFiles.ts")
LICENSES = os.path.join(DIR, "LICENSES.json")
EXTS = (".m4a", ".mp3")


def write_registry(ids_to_files):
    lines = [
        "// GENERATED by scripts/narration/install_scene_sounds.py — do not edit by hand.",
        "// Scene sounds that ship inside the app (assets/scene-sounds/). A cue that names a sound",
        "// missing here is skipped, so cue sheets can be written before the sound files exist.",
        "export const SCENE_SOUND_FILES: Record<string, number> = {",
    ]
    for sid, fname in sorted(ids_to_files.items()):
        lines.append(f'  "{sid}": require("@/assets/scene-sounds/{fname}") as number,')
    lines += ["};", ""]
    open(REGISTRY, "w").write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src")
    ap.add_argument("--allow-unlicensed", action="store_true")
    ap.add_argument("--clean", action="store_true")
    a = ap.parse_args()
    os.makedirs(DIR, exist_ok=True)

    if a.clean:
        for f in glob.glob(os.path.join(DIR, "*")):
            if os.path.basename(f) != "LICENSES.json":
                os.remove(f)
        write_registry({})
        print("cleaned: no scene sounds installed")
        return

    if a.src:
        for f in glob.glob(os.path.join(os.path.expanduser(a.src), "*")):
            if f.lower().endswith(EXTS):
                shutil.copy2(f, os.path.join(DIR, os.path.basename(f)))

    files = {os.path.splitext(os.path.basename(f))[0]: os.path.basename(f)
             for f in sorted(glob.glob(os.path.join(DIR, "*"))) if f.lower().endswith(EXTS)}
    licenses = json.load(open(LICENSES)) if os.path.exists(LICENSES) else {}
    missing = [sid for sid in files if sid not in licenses]
    if missing and not a.allow_unlicensed:
        print("STOP — no license record in assets/scene-sounds/LICENSES.json for:", ", ".join(missing))
        sys.exit(1)
    write_registry(files)
    total = sum(os.path.getsize(os.path.join(DIR, f)) for f in files.values()) / 1e6
    print(f"{len(files)} scene sounds registered ({total:.1f} MB)" + ("  [UNLICENSED — test only]" if missing else ""))


if __name__ == "__main__":
    main()
