function buildSet(): Set<string> {
  const set = new Set<string>();
  for (const [book, chapters] of Object.entries(RAW)) {
    const displayBook = book === "Psalms" ? "Psalm" : book;
    for (const [chapStr, ranges] of Object.entries(chapters)) {
      const chap = Number(chapStr);
      for (const vr of ranges) {
        if (typeof vr === "number") {
          set.add(`${displayBook} ${chap}:${vr}`);
        } else {
          for (let v = vr[0]; v <= vr[1]; v++) {
            set.add(`${displayBook} ${chap}:${v}`);
          }
        }
      }
    }
  }
  return set;
}

const CHRIST_VERSES = buildSet();

export function isChristVerse(ref: string): boolean {
  return CHRIST_VERSES.has(ref);
}
